#!/usr/bin/env python3
# BFI brightness-preserving (Lottes-style) tables for the hz120 build.
#
# For each NES palette code c (treated as sRGB, GAMMA=2.4, exactly the
# Blur Busters / Lottes reference shader's transfer pair), the linear-light
# photon budget of the pixel over one content frame is L = 2*v (gain 1.0:
# unchanged average brightness). The lit refresh carries HI = encode(min(1,L))
# and the other refresh carries LO = encode(L - min(1,L)), so dark/mid pixels
# (v <= 0.5) land wholly in one refresh (full 50 % clarity) and only bright
# pixels spill over, with no loss of average brightness.
#
# Usage: python3 tools/bfi_lottes.py   (run from the repo root)
# Prints the Verilog assigns to paste into src/nes2hdmi.sv (HZ120 block).
# The sim reads the same mapping from sim/framelock/bfi_lottes.hex, which is
# generated by: python3 tools/bfi_lottes.py --hex > sim/framelock/bfi_lottes.hex
import re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

GAMMA = 2.4  # reference shader GAMMA constant (crt-simulator.glsl)

def srgb2linear(c):
    return ((c + 0.055) / 1.055) ** GAMMA if c > 0.04045 else c / 12.92

def linear2srgb(v):
    return v * 12.92 if v <= 0.0031308 else v ** (1.0 / GAMMA) * 1.055 - 0.055

def pair(code):
    v = srgb2linear(code / 255.0)
    L = 2.0 * v
    hi = min(255, max(0, round(255 * linear2srgb(min(1.0, L)))))
    lo = min(255, max(0, round(255 * linear2srgb(L - min(1.0, L)))))
    return hi, lo

src = open(os.path.join(ROOT, 'src', 'nes2hdmi.sv')).read()
pal = {}
for m in re.finditer(r"assign NES_PALETTE\[(\d+)\] = 24'h([0-9a-fA-F]{6});", src):
    pal[int(m.group(1))] = m.group(2).lower()
assert len(pal) == 64, len(pal)

def rgb_pair(hex6):
    r, g, b = (pair(int(hex6[i:i + 2], 16)) for i in (0, 2, 4))
    return (f"{r[0]:02x}{g[0]:02x}{b[0]:02x}", f"{r[1]:02x}{g[1]:02x}{b[1]:02x}")

hi = [rgb_pair(pal[i])[0] for i in range(64)]
lo = [rgb_pair(pal[i])[1] for i in range(64)]
bhi, blo = rgb_pair('303030')  # border colour

if '--hex' in sys.argv:
    # 256-entry per-code {HI,LO} for the sim (sim/framelock/bfi_lottes.hex)
    for code in range(256):
        h, l = pair(code)
        sys.stdout.write(f"{h:02x}{l:02x}\n")
else:
    print("// BEGIN Lottes tables (tools/bfi_lottes.py, sRGB GAMMA=2.4).")
    print("// Per input code: HI = lit-refresh value, LO = remainder refresh.")
    for i in range(64):
        print(f"// [{i}] {pal[i]} -> HI {hi[i]} LO {lo[i]}")
    print("// HI table (lit refresh):")
    for i in range(64):
        print(f"assign NES_PALETTE_HI[{i}] = 24'h{hi[i]};")
    print("// LO table (remainder refresh):")
    for i in range(64):
        print(f"assign NES_PALETTE_LO[{i}] = 24'h{lo[i]};")
    print(f"// border 303030 -> HI 24'h{bhi} LO 24'h{blo}")
    worst = 0.0
    for code in range(256):
        h, l = pair(code)
        v = srgb2linear(code / 255.0)
        worst = max(worst, abs(srgb2linear(h / 255.0) + srgb2linear(l / 255.0) - 2 * v))
    print(f"// worst average-light error: {worst:.5f} linear ({100 * worst:.3f}% of full white).", file=sys.stderr)
