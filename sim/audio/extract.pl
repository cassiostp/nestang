#!/usr/bin/perl
# Build iverilog-compilable copies of the three audio modules the testbench
# exercises, mechanically from the real sources:
#   APUMixer       (src/apu.v)           LUT assignment patterns become initial
#                                        assignments; iverilog has no patterns.
#   SS5b_mixed     (src/mappers/Sunsoft.sv)  verbatim
#   namco163_mixed (src/mappers/Namco.sv)    verbatim
# The sound generators inside the two _mixed modules are stubbed by the
# testbench, so only their mixing arithmetic is taken from the sources.
# Output goes to build/ (not committed). Fails unless every LUT is whole.
use strict;
use warnings;

my $rtl = $ARGV[0] or die "usage: extract.pl <src-dir>\n";
mkdir "build";

sub slurp {
    my ($path) = @_;
    open my $fh, "<", $path or die "$path: $!\n";
    local $/;
    return <$fh>;
}

sub module_text {
    my ($text, $name) = @_;
    $text =~ /(^module\s+\Q$name\E\b.*?^endmodule\b)/ms
        or die "module $name not found\n";
    return $1;
}

my %want_count = (pulse_lut => 32, tri_lut => 16, noise_lut => 16,
                  dmc_lut => 128, mix_lut => 512);

my $apu = module_text(slurp("$rtl/apu.v"), "APUMixer");
$apu =~ s/assign\s+(\w+_lut)\s*=\s*'\{(.*?)\};/transform_lut($1, $2)/ges;
sub transform_lut {
    my ($name, $body) = @_;
    my @vals = grep { /\S/ } map { s/^\s+|\s+$//gr } split /,/, $body;
    my $want = $want_count{$name} or die "unexpected LUT $name\n";
    die "$name: got " . scalar(@vals) . " entries, want $want\n"
        unless @vals == $want;
    my $out = "initial begin\n";
    $out .= "\t$name\[$_] = $vals[$_];\n" for 0 .. $#vals;
    return $out . "end";
}
die " APUMixer still has an assignment pattern\n" if $apu =~ /assign\s+\w+_lut/;

my $ss5b = module_text(slurp("$rtl/mappers/Sunsoft.sv"), "SS5b_mixed");
my $n163 = module_text(slurp("$rtl/mappers/Namco.sv"), "namco163_mixed");

open my $out, ">", "build/audio_modules.v" or die $!;
print $out "// Generated by extract.pl from the real sources; do not edit.\n";
print $out "$apu\n\n$ss5b\n\n$n163\n";
close $out;
print "extract: APUMixer (5 LUTs whole), SS5b_mixed, namco163_mixed -> build/audio_modules.v\n";
